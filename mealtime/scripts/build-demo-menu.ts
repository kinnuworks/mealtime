// Builds server/lib/demo-menu.ts from the saved recipe snapshots
// (fixtures/recipes) and, if present, the steps the agent produced for them
// (fixtures/demo-steps.json, written by scripts/capture-demo-steps.ts).
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { isoMinutes } from "../server/lib/recipe.js";

const idx = JSON.parse(readFileSync("fixtures/recipes/index.json", "utf8")) as { demo: string[] };
const dishes = idx.demo.map((slug, i) => {
  const r = JSON.parse(readFileSync(`fixtures/recipes/${slug}.json`, "utf8"));
  return {
    id: `d${i + 1}`,
    name: r.name,
    sourceUrl: r.url,
    site: r.site,
    stated: { prep: isoMinutes(r.prepTime), cook: isoMinutes(r.cookTime), total: isoMinutes(r.totalTime) },
    ingredients: r.ingredients,
    instructions: r.instructions,
    status: "needs-steps",
  };
});
const steps = existsSync("fixtures/demo-steps.json") ? JSON.parse(readFileSync("fixtures/demo-steps.json", "utf8")) : [];
for (const d of dishes) if (steps.some((s: { dishId: string }) => s.dishId === d.id)) d.status = "ready";
writeFileSync(
  "server/lib/demo-menu.ts",
  `// Generated by scripts/build-demo-menu.ts from fixtures/recipes. Do not edit by hand.
import type { Dish, KStep } from "./kitchen.js";

export const DEMO_DISHES: Dish[] = ${JSON.stringify(dishes, null, 2)};
export const DEMO_STEPS: KStep[] = ${JSON.stringify(steps, null, 2)};
`,
);
console.log(`demo menu: ${dishes.length} dishes, ${steps.length} steps`);
